/* ══════════════════════════════════════════════════════════════════════════════
 * angr Symbolic Execution Probe Markers
 *
 * These NOP-based probes provide angr with unambiguous addresses to:
 *   1. Find the start of the crypto operation (MARK_START → entry hook)
 *   2. Find the end   of the crypto operation (MARK_END   → exit  hook)
 *
 * The volatile asm NOP sequences are 2 bytes each on x86/aarch64, preventing
 * the compiler from optimising them away, and giving angr a stable byte pattern
 * to search for in the binary.
 * ══════════════════════════════════════════════════════════════════════════════
 */

#if defined(__x86_64__) || defined(__i386__)
/* Two consecutive NOPs (0x90 0x90) on x86 — easy to find in binary */
#define TEST_MARK_START() __asm__ volatile("nop\n\tnop\n\t" ::: "memory")
#define TEST_MARK_END() __asm__ volatile("nop\n\tnop\n\tnop\n\t" ::: "memory")
#elif defined(__aarch64__) || defined(__arm__)
/* NOP on ARM = 0xd503201f (AArch64) or 0xe320f000 (ARM) */
#define TEST_MARK_START() __asm__ volatile("nop\n\tnop\n\t" ::: "memory")
#define TEST_MARK_END() __asm__ volatile("nop\n\tnop\n\tnop\n\t" ::: "memory")
#elif defined(__riscv)
#define TEST_MARK_START() __asm__ volatile("nop\n\tnop\n\t" ::: "memory")
#define TEST_MARK_END() __asm__ volatile("nop\n\tnop\n\tnop\n\t" ::: "memory")
#else
/* Fallback: compiler memory barrier only */
#define TEST_MARK_START() __asm__ volatile("" ::: "memory")
#define TEST_MARK_END() __asm__ volatile("" ::: "memory")
#endif

/* ══════════════════════════════════════════════════════════════════════════════
 * Constant-time memory comparison
 *
 * Prevents angr from branching on intermediate comparison results when
 * verifying output correctness. All bytes are always compared.
 * ══════════════════════════════════════════════════════════════════════════════
 */

/**
 * @brief Constant-time memory comparison.
 * @return 0 if equal, non-zero otherwise.
 */
static inline int ct_memcmp(const void *a, const void *b, size_t n) {
  const volatile uint8_t *pa = (const volatile uint8_t *)a;
  const volatile uint8_t *pb = (const volatile uint8_t *)b;
  uint8_t diff = 0;
  for (size_t i = 0; i < n; i++) {
    diff |= pa[i] ^ pb[i];
  }
  return (int)diff;
}

/* ══════════════════════════════════════════════════════════════════════════════
 * Test result reporter
 * ══════════════════════════════════════════════════════════════════════════════
 */

/**
 * @brief Print test result in machine-parseable format.
 * @param name      Algorithm/test name
 * @param ok        Non-zero = PASS, 0 = FAIL
 * @param output    Pointer to output bytes (may be NULL)
 * @param out_len   Number of bytes from @p output to hex-print
 */
static inline void test_print_result(const char *name, int ok,
                                     const uint8_t *output, size_t out_len) {
  printf("RESULT %-30s %s", name, ok ? "PASS" : "FAIL");
  if (output != NULL && out_len > 0) {
    printf(" [");
    for (size_t i = 0; i < out_len && i < 32; i++) {
      printf("%02x", output[i]);
    }
    if (out_len > 32)
      printf("...");
    printf("]");
  }
  printf("\n");
  fflush(stdout);
}

/* TEST_VERIFY: check output matches expected, print result, return 1 on fail */
#define TEST_VERIFY(got, expected, size, name)                                 \
  do {                                                                         \
    int _ok = (ct_memcmp((got), (expected), (size)) == 0);                     \
    test_print_result((name), _ok, (got), (size));                             \
    if (!_ok)                                                                  \
      return 1;                                                                \
  } while (0)

